/** A function's letters. */
export const ARGUMENT_KINDS = new Map();
for (const [key, names] of Object.entries(BY_KIND)) for (const name of names.split(/\s+/)) ARGUMENT_KINDS.set(name, key.replace(/_+$/, ''));

